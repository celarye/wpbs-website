"""Generates the API reference pages from the WIT files.

A package's `world.wit` becomes its index page, and each of its other files a
page below it. A package without a `world.wit` gets a single page.

Usage: python3 reference.py path/to/wit
"""

import pathlib
import re
import sys
import textwrap

ROOT = pathlib.Path(sys.argv[1]).resolve()
OUT = pathlib.Path(__file__).resolve().parent / "content/docs/development/plugins/reference"

# Source directory, page path without extension, title, description, and weight.
PACKAGES = [
    ("core", "core", "Core", "Persistent storage, logging, and host and plugin lifecycle operations.", 1),
    ("deps/wpbs-shared", "dependencies/shared", "Shared", "Shared payload and error types.", 1),
    ("deps/wasi-keyvalue", "dependencies/keyvalue", "Keyvalue", "Key-value stores, with atomic and batch operations.", 2),
    ("services/scheduler", "services/scheduler", "Scheduler", "Crons on cron expressions and one-shots at a point in time.", 1),
    ("services/discord", "services/discord", "Discord", "Discord events, requests, interactions, and voice channels.", 2),
]

# Sections that group the pages above.
SECTIONS = [
    ("dependencies/_index.md", "Dependencies", "Packages the other packages build on.", 2),
    ("services/_index.md", "Services", "The optional service packages.", 3),
]

KINDS = {
    "func": "Function",
    "record": "Record",
    "variant": "Variant",
    "enum": "Enum",
    "flags": "Flags",
    "type": "Type",
}

# Page titles that are not just the file name in title case.
TITLES = {"http": "HTTP"}

# Parts of the vendored key-value package that wpbs does not provide.
SKIP_FILES = {"watch.wit"}
SKIP_WORLDS = {"watch-service"}

NOTICE = (
    "# This file is autogenerated and should not be manually edited.\n"
    "# Regenerate it with `python3 reference.py path/to/wit`, using the WIT files\n"
    "# from https://github.com/wpbs-rs/wit."
)

DECLARATION = re.compile(
    r"^(?:(?P<kind>record|variant|enum|flags|resource|type|interface|world)\s+(?P<name>[\w-]+)"
    r"|(?P<func>[\w-]+)\s*:\s*(?:async\s+)?(?:static\s+)?func\b"
    r"|(?P<ctor>constructor)\s*\()"
)


def parse(source):
    """Yields (parents, docs, kind, name, code) for each declaration."""
    text = re.sub(r"/\*.*?\*/", "", source, flags=re.S).expandtabs(4)
    lines = text.splitlines()
    docs = []
    stack = []
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if line.startswith("///"):
            docs.append(line[3:][1:] if line[3:].startswith(" ") else line[3:])
            continue
        if not line or line.startswith("//") or line.startswith("@since") or line.startswith("use "):
            continue
        if line.startswith("package "):
            docs = []
            continue
        if line == "}":
            if stack:
                stack.pop()
            docs = []
            continue
        match = DECLARATION.match(line)
        if not match:
            docs = []
            continue
        kind = match.group("kind") or ("constructor" if match.group("ctor") else "func")
        name = match.group("name") or match.group("func") or "constructor"
        block = [lines[i - 1]]
        if kind in ("interface", "resource", "world"):
            if kind == "world":
                depth = 1
                while depth:
                    block.append(lines[i])
                    depth += lines[i].count("{") - lines[i].count("}")
                    i += 1
                code = clean(block)
                yield list(stack), docs, kind, name, code
            else:
                yield list(stack), docs, kind, name, None
                stack.append(name)
            docs = []
            continue
        if line.endswith("{"):
            depth = 1
            while depth:
                block.append(lines[i])
                depth += lines[i].count("{") - lines[i].count("}")
                i += 1
        else:
            while not block[-1].rstrip().endswith(";"):
                block.append(lines[i])
                i += 1
        yield list(stack), docs, kind, name, clean(block)
        docs = []


def clean(block):
    kept = [l for l in block if not l.strip().startswith("@since")]
    return textwrap.dedent("\n".join(kept)).strip()


MEMBER = re.compile(r"(?:import|export)\s+([\w-]+)|([\w-]+)")


def members(text):
    """Splits the doc comments of a block's members, such as fields and cases, from its code.

    Returns the code without them, and a Markdown list of the documented members.
    """
    lines = text.splitlines()
    kept = []
    items = []
    docs = []
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("///"):
            docs.append(stripped[3:].strip())
            continue
        if not stripped:
            following = next((l.strip() for l in lines[i + 1 :] if l.strip()), "")
            if following.startswith("///"):
                continue
        if docs and stripped:
            match = MEMBER.match(stripped)
            items.append(f"- `{match.group(1) or match.group(2)}`: {' '.join(docs)}")
            docs = []
        kept.append(line)
    return "\n".join(kept), "\n".join(items)


def code(text, parents=()):
    """A WIT code block, wrapped in its interface and resource so it is valid WIT."""
    for depth, (keyword, name) in reversed(list(enumerate(parents))):
        text = f"{keyword} {name} {{\n" + textwrap.indent(text, "    ") + "\n}"
    return f"```wit\n{text}\n```"


def render(directory):
    """Returns the package name and the sections of each file, by file stem."""
    package = None
    files = {}
    for path in sorted((ROOT / directory).glob("*.wit"), key=lambda p: (p.name != "world.wit", p.name)):
        if path.name in SKIP_FILES:
            continue
        source = path.read_text()
        match = re.search(r"^package\s+([\w:-]+)", source, re.M)
        package = package or (match and match.group(1))
        files[path.stem] = render_file(source)
    return package, files


def render_file(source):
    sections = []
    params = []
    params_interface = None
    for parents, docs, kind, name, body in parse(source):
        context = [("interface", parents[0])] + [("resource", r) for r in parents[1:]] if parents else []
        prose = "\n".join(docs).strip()
        if kind == "world":
            if name in SKIP_WORLDS:
                continue
            body, items = members(body)
            sections.append("\n\n".join(p for p in [f"## World `{name}`", prose, items, code(body)] if p))
        elif kind == "interface":
            sections.append("\n\n".join(p for p in [f"## Interface `{name}`", prose] if p))
        elif kind == "resource":
            sections.append(f"### Resource `{name}`\n\n{prose}".rstrip())
        elif kind == "record" and name.endswith("-params") and not prose:
            params.append(body)
            params_interface = parents[0]
        else:
            if len(parents) == 2:
                heading = "####"
                if kind == "constructor":
                    label = "Constructor"
                elif "static func" in body:
                    label = f"Static function `{name}`"
                else:
                    label = f"Method `{name}`"
            else:
                heading = "###"
                label = f"{KINDS[kind]} `{name}`"
            body, items = members(body)
            parts = [f"{heading} {label}"]
            if prose:
                parts.append(prose)
            if items:
                parts.append(items)
            parts.append(code(body, context))
            sections.append("\n\n".join(parts))
    if params:
        sections.append(
            "### Route parameters\n\nRecords for `route` cases that take more than one value.\n\n"
            + code("\n\n".join(params), [("interface", params_interface)])
        )
    return sections


def write(page, title, description, weight, intro, sections, section=False, children=None):
    path = OUT / page
    path.parent.mkdir(parents=True, exist_ok=True)
    # Zola needs the front matter first, so the notice is a TOML comment inside it.
    front = f'+++\n{NOTICE}\ntitle = "{title}"\ndescription = "{description}"\nweight = {weight}\n'
    if section:
        front += 'sort_by = "weight"\n'
    if children:
        # The template lists the child pages under this heading.
        front += f'\n[extra]\nchildren_heading = "{children}"\n'
    front += "+++\n\n"
    body = "\n\n".join([intro] + sections) if intro else "\n\n".join(sections)
    path.write_text(front + body.strip() + "\n")


def interfaces(sections):
    """A description of a page from the interfaces it holds, in plain text."""
    names = [s.split("`")[1] for s in sections if s.startswith("## Interface ")]
    if len(names) == 1:
        return f"The {names[0]} interface."
    return f"The {', '.join(names[:-1])} and {names[-1]} interfaces."


def main():
    # Every page below the hand-written index is generated, so start clean.
    for path in OUT.rglob("*.md"):
        if path != OUT / "_index.md":
            path.unlink()
    for page, title, description, weight in SECTIONS:
        write(page, title, description, weight, None, [], section=True)
    for directory, page, title, description, weight in PACKAGES:
        package, files = render(directory)
        intro = f"Package `{package}`."
        if directory == "deps/wasi-keyvalue":
            intro += (
                " The [WASI key-value](https://github.com/WebAssembly/wasi-keyvalue) "
                "API, included in the core package for storage."
            )
        if "world" not in files:
            sections = [section for file in files.values() for section in file]
            write(f"{page}.md", title, description, weight, intro, sections)
            continue
        write(f"{page}/_index.md", title, description, weight, intro, files.pop("world"), section=True, children="Interfaces")
        for subweight, (stem, sections) in enumerate(files.items(), 1):
            subtitle = TITLES.get(stem, stem.replace("-", " ").title())
            write(f"{page}/{stem}.md", subtitle, interfaces(sections), subweight, None, sections)


if __name__ == "__main__":
    main()
